CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL CHECK (password_hash LIKE '$2%'),
    role VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (role = 'ADMIN'),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(140) NOT NULL UNIQUE,
    parent_id BIGINT REFERENCES categories(id),
    CONSTRAINT category_not_own_parent CHECK (parent_id IS DISTINCT FROM id)
);
CREATE INDEX ix_categories_parent ON categories(parent_id);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(150) NOT NULL,
    variant VARCHAR(150) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    image_url VARCHAR(2048),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_products_category_status ON products(category_id, status);

CREATE TABLE stores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    store_id BIGINT NOT NULL REFERENCES stores(id),
    price NUMERIC(12,2) NOT NULL CHECK (price > 0),
    previous_price NUMERIC(12,2) CHECK (previous_price > 0),
    previous_price_evidence VARCHAR(2048),
    affiliate_url VARCHAR(2048) NOT NULL CHECK (affiliate_url ~ '^https://[^[:space:]]+$'),
    shipping_cost NUMERIC(12,2) CHECK (shipping_cost >= 0),
    purchase_conditions TEXT,
    last_checked_at TIMESTAMPTZ NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT previous_price_requires_evidence CHECK (
        previous_price IS NULL OR length(trim(previous_price_evidence)) > 0 AND previous_price_evidence IS NOT NULL
    )
);
CREATE INDEX ix_offers_product_active_price ON offers(product_id, active, price);
CREATE INDEX ix_offers_store ON offers(store_id);
CREATE INDEX ix_offers_featured ON offers(featured) WHERE active AND featured;

CREATE TABLE price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES offers(id),
    price NUMERIC(12,2) NOT NULL CHECK (price > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_price_history_offer_time ON price_history(offer_id, recorded_at DESC);

-- Registra preço inicial e alterações mesmo quando feitas diretamente no banco.
CREATE FUNCTION record_offer_price() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO price_history(offer_id, price) VALUES (NEW.id, NEW.price);
    ELSIF NEW.price IS DISTINCT FROM OLD.price THEN
        INSERT INTO price_history(offer_id, price) VALUES (NEW.id, NEW.price);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER offer_price_history AFTER INSERT OR UPDATE OF price ON offers
FOR EACH ROW EXECUTE FUNCTION record_offer_price();
