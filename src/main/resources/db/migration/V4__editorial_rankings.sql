CREATE TABLE rankings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    criteria VARCHAR(3000) NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE ranking_items (
    ranking_id BIGINT NOT NULL REFERENCES rankings(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    position INTEGER NOT NULL CHECK (position BETWEEN 1 AND 10),
    reason VARCHAR(1000) NOT NULL CHECK (length(trim(reason)) > 0),
    PRIMARY KEY (ranking_id, product_id),
    UNIQUE (ranking_id, position)
);
CREATE INDEX ix_ranking_items_product ON ranking_items(product_id);
CREATE INDEX ix_rankings_published ON rankings(updated_at DESC) WHERE published;
